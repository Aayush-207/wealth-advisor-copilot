/* Browser smoke checks. See docs/redesign/VERIFICATION.md for setup. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const { spawn } = require('node:child_process');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const root = path.resolve(__dirname, '..');
const base = process.env.SMOKE_BASE_URL || 'http://127.0.0.1:3000';
const screenshots = path.join(root, 'docs/redesign/screenshots');
let server;
async function startServer() {
  if (process.env.SMOKE_BASE_URL) return;
  server = spawn(process.execPath, ['node_modules/next/dist/bin/next', 'start', '--hostname', '127.0.0.1', '--port', '3000'], { cwd: path.join(root, 'frontend'), stdio: ['ignore', 'pipe', 'pipe'] });
  await new Promise((resolve, reject) => {
    server.stdout.on('data', b => { if (b.toString().includes('Ready')) resolve(); });
    server.stderr.on('data', b => process.stderr.write(b));
    server.on('error', reject);
    server.on('exit', c => reject(new Error(`Server exited: ${c}`)));
  });
}
