    await page.getByRole('button', { name: 'Copy answer' }).click();
    assert.ok((await page.evaluate(() => navigator.clipboard.readText())).includes('PDF p. 20'));
    await page.getByRole('button', { name: 'Request specialist review' }).click();
    await visible('.toast', 'Saved');
    await page.getByRole('button', { name: 'Fee Structures', exact: true }).click();
    await visible('.answer-card', 'Start with the right share class.');
    assert.ok(!(await page.locator('.answer-card').last().textContent()).includes('1.50%'));
